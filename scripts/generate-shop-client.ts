/** Generate only the public catalogue, quote and checkout wire contracts. */
import { resolve } from "node:path";
import { publicTypeNames } from "./public-type-names";
import { documentWireTypes } from "./wire-documentation";

const inputs = Bun.argv.slice(2);
if (inputs.length < 2 || inputs.length > 3)
  throw new Error(
    "Usage: bun run generate:shop-client catalogue-openapi.json checkout-openapi.json [legal-openapi.json]",
  );
type Schema = {
  $ref?: string;
  type?: string;
  enum?: unknown[];
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  anyOf?: Schema[];
  oneOf?: Schema[];
  allOf?: Schema[];
  additionalProperties?: Schema | boolean;
};
type Operation = {
  requestBody?: { content: Record<string, { schema: Schema }> };
  responses: Record<string, { content?: Record<string, { schema: Schema }> }>;
};
type Document = {
  components: { schemas: Record<string, Schema> };
  paths: Record<string, Record<string, Operation>>;
};
const documents = await Promise.all(
  inputs.map(
    async (input) => (await Bun.file(resolve(input)).json()) as Document,
  ),
);
// Parallel backend exports contain additive contract changes. Retain every field.
const schemas: Record<string, Schema> = {};
for (const document of documents) {
  for (const [name, schema] of Object.entries(document.components.schemas)) {
    const previous = schemas[name];
    schemas[name] =
      previous?.properties && schema.properties
        ? {
            ...previous,
            ...schema,
            properties: { ...previous.properties, ...schema.properties },
            required: [
              ...new Set([
                ...(previous.required ?? []),
                ...(schema.required ?? []),
              ]),
            ],
          }
        : schema;
  }
}
const needed = new Set<string>();
function render(s: Schema): string {
  if (s.$ref) {
    const n = s.$ref.split("/").at(-1);
    if (!n || !schemas[n]) throw new Error(`Unresolved ${s.$ref}`);
    needed.add(n);
    return n;
  }
  if (s.enum) return s.enum.map((x) => JSON.stringify(x)).join(" | ");
  if (s.anyOf || s.oneOf)
    return (s.anyOf ?? s.oneOf ?? []).map(render).join(" | ");
  if (s.allOf) return s.allOf.map(render).join(" & ");
  if (s.type === "null") return "null";
  if (s.type === "array") return `Array<${render(s.items ?? {})}>`;
  if (s.type === "integer" || s.type === "number") return "number";
  if (s.type === "string" || s.type === "boolean") return s.type;
  if (s.properties)
    return `{ ${Object.entries(s.properties)
      .map(
        ([k, v]) =>
          `${JSON.stringify(k)}${s.required?.includes(k) ? "" : "?"}: ${render(v)};`,
      )
      .join(" ")} }`;
  if (typeof s.additionalProperties === "object")
    return `Record<string, ${render(s.additionalProperties)}>`;
  return "unknown";
}
const routes = {
  catalogue: [0, "/api/shop/articles/catalogue", "get"],
  vouchers: [0, "/api/shop/articles/", "get"],
  article: [0, "/api/shop/articles/{article_slug}", "get"],
  settings: [1, "/api/shop/settings", "get"],
  quote: [1, "/api/shop/cart/", "post"],
  checkout: [1, "/api/shop/checkout/create-checkout-session", "post"],
  order: [1, "/api/shop/orders/{order_id}", "get"],
  confirm: [1, "/api/shop/checkout/confirm-checkout", "post"],
} as const;
let operations = "export type ShopOperations = {\n";
let paths = "export const shopPaths = {\n";
for (const [name, [documentIndex, path, method]] of Object.entries(routes)) {
  const op = documents[documentIndex].paths[path]?.[method];
  if (!op) throw new Error(`Missing ${method} ${path}`);
  const response = op.responses["200"]?.content?.["application/json"]?.schema;
  const body = op.requestBody?.content["application/json"]?.schema;
  operations += `${name}: { body: ${body ? render(body) : "undefined"}; response: ${response ? render(response) : "unknown"} };\n`;
  paths += `${name}: ${JSON.stringify(path)},\n`;
}
let output =
  "// Generated by scripts/generate-shop-client.ts from the catalogue and checkout OpenAPI exports.\n";
for (const name of needed)
  output += `export type ${name} = ${render(schemas[name])};\n`;
await Bun.write(
  "src/shop-wire.ts",
  documentWireTypes(
    publicTypeNames(`${output + operations}};\n${paths}} as const;\n`),
  ),
);
const child = Bun.spawn(
  ["bun", "run", "format:generated", "src/shop-wire.ts"],
  { stdout: "inherit", stderr: "inherit" },
);
if ((await child.exited) !== 0) throw new Error("Formatting failed");
